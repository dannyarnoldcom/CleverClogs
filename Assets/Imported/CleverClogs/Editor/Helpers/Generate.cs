using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;

namespace DADC.Clogs
{
    public static class Generate
    {
        public const string Header = "// <auto-generated>";

        private const string uiElementsNamespace = "UnityEngine.UIElements";
        private const string fallbackType = "VisualElement";

        // Names the generated class already uses, or inherits from System.Object.
        private static readonly string[] reservedMembers =
        {
            "Element", "UxmlPath", "Root", "NameOf", "Q", "Get",
            "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "Finalize"
        };

        private struct Member
        {
            public string identifier;
            public string name;
            public string type;
        }

        /// <summary>
        /// Builds the source of a helper class holding an enum of the named elements
        /// in a UXML file and a typed property for each of them.
        /// </summary>
        public static string BuildSource(string className, string uxmlPath, IList<Element> elements, string namespaceName, out List<string> warnings)
        {
            warnings = new List<string>();
            className = ToIdentifier(className);
            bool editorOnly;
            List<Member> members = BuildMembers(className, elements, warnings, out editorOnly);

            bool hasNamespace = !string.IsNullOrWhiteSpace(namespaceName);
            string indent = hasNamespace ? "    " : "";
            StringBuilder sb = new StringBuilder();

            sb.AppendLine(Header);
            sb.AppendLine("//     Generated by Clever Clogs from " + uxmlPath);
            sb.AppendLine("//     Changes to this file are lost when it is regenerated.");
            sb.AppendLine("// </auto-generated>");
            if (editorOnly) sb.AppendLine("#if UNITY_EDITOR");
            sb.AppendLine("using UnityEngine.UIElements;");
            sb.AppendLine();
            if (hasNamespace)
            {
                sb.AppendLine("namespace " + namespaceName.Trim());
                sb.AppendLine("{");
            }

            sb.AppendLine(indent + "public sealed class " + className);
            sb.AppendLine(indent + "{");

            sb.AppendLine(indent + "    public enum Element");
            sb.AppendLine(indent + "    {");
            foreach (Member member in members) sb.AppendLine(indent + "        " + member.identifier + ",");
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            sb.AppendLine(indent + "    public const string UxmlPath = " + ToLiteral(uxmlPath) + ";");
            sb.AppendLine();

            sb.AppendLine(indent + "    private static readonly string[] names =");
            sb.AppendLine(indent + "    {");
            foreach (Member member in members) sb.AppendLine(indent + "        " + ToLiteral(member.name) + ",");
            sb.AppendLine(indent + "    };");
            sb.AppendLine();

            sb.AppendLine(indent + "    /// <summary>The name the element has in the UXML file.</summary>");
            sb.AppendLine(indent + "    public static string NameOf(Element element)");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        return names[(int)element];");
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            sb.AppendLine(indent + "    /// <summary>Queries any tree cloned from the UXML file without creating a " + className + ".</summary>");
            sb.AppendLine(indent + "    public static T Q<T>(VisualElement root, Element element) where T : VisualElement");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        return root.Q<T>(NameOf(element));");
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            sb.AppendLine(indent + "    public VisualElement Root { get; }");
            foreach (Member member in members) sb.AppendLine(indent + "    public " + member.type + " " + member.identifier + " { get; }");
            sb.AppendLine();

            sb.AppendLine(indent + "    public " + className + "(VisualElement root)");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        if (root == null) throw new global::System.ArgumentNullException(nameof(root));");
            sb.AppendLine(indent + "        Root = root;");
            foreach (Member member in members)
            {
                sb.AppendLine(indent + "        " + member.identifier + " = root.Q<" + member.type + ">(" + ToLiteral(member.name) + ");");
            }
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            sb.AppendLine(indent + "    public VisualElement Get(Element element)");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        switch (element)");
            sb.AppendLine(indent + "        {");
            foreach (Member member in members)
            {
                sb.AppendLine(indent + "            case Element." + member.identifier + ": return " + member.identifier + ";");
            }
            sb.AppendLine(indent + "            default: throw new global::System.ArgumentOutOfRangeException(nameof(element));");
            sb.AppendLine(indent + "        }");
            sb.AppendLine(indent + "    }");
            sb.AppendLine();

            sb.AppendLine(indent + "    public T Get<T>(Element element) where T : VisualElement");
            sb.AppendLine(indent + "    {");
            sb.AppendLine(indent + "        return (T)Get(element);");
            sb.AppendLine(indent + "    }");

            sb.AppendLine(indent + "}");
            if (hasNamespace) sb.AppendLine("}");
            if (editorOnly) sb.AppendLine("#endif");

            return sb.ToString();
        }

        /// <summary>
        /// Writes the source to folder/className.cs and imports it. Returns the asset path.
        /// </summary>
        public static string WriteFile(string folder, string className, string source)
        {
            if (string.IsNullOrWhiteSpace(folder)) throw new ArgumentException("No output folder set");

            folder = folder.Replace('\\', '/').TrimEnd('/');
            string path = folder + "/" + ToIdentifier(className) + ".cs";

            if (File.Exists(path) && !File.ReadAllText(path).StartsWith(Header))
            {
                throw new IOException(path + " already exists and was not generated by Clever Clogs");
            }

            Directory.CreateDirectory(folder);
            File.WriteAllText(path, source, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(path);
            return path;
        }

        /// <summary>
        /// Turns any string into a PascalCase C# identifier, "submit-button" becomes "SubmitButton".
        /// </summary>
        public static string ToIdentifier(string name)
        {
            StringBuilder sb = new StringBuilder();
            bool startOfWord = true;

            foreach (char c in name ?? string.Empty)
            {
                if (!char.IsLetterOrDigit(c))
                {
                    startOfWord = true;
                    continue;
                }
                sb.Append(startOfWord ? char.ToUpperInvariant(c) : c);
                startOfWord = false;
            }

            if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
            return sb.ToString();
        }

        private static List<Member> BuildMembers(string className, IList<Element> elements, List<string> warnings, out bool editorOnly)
        {
            List<Member> members = new List<Member>();
            HashSet<string> names = new HashSet<string>();
            HashSet<string> identifiers = new HashSet<string>(reservedMembers) { className };
            editorOnly = false;

            foreach (Element element in elements)
            {
                if (string.IsNullOrWhiteSpace(element.name)) continue;

                if (!names.Add(element.name))
                {
                    warnings.Add("\"" + element.name + "\" is used more than once, only the first is generated");
                    continue;
                }

                string identifier = ToIdentifier(element.name);
                if (identifiers.Contains(identifier))
                {
                    string renamed = identifier + "Element";
                    for (int i = 2; identifiers.Contains(renamed); i++) renamed = identifier + i;
                    warnings.Add("\"" + element.name + "\" is generated as " + renamed + ", " + identifier + " is already taken");
                    identifier = renamed;
                }
                identifiers.Add(identifier);

                Type type = GetAccessibleType(element.elementType);
                if (type != null && IsEditorType(type)) editorOnly = true;

                members.Add(new Member { identifier = identifier, name = element.name, type = GetTypeName(type) });
            }

            return members;
        }

        // Internal and generic element types can't be named in generated code, their closest usable base can.
        private static Type GetAccessibleType(Type type)
        {
            if (type == null || !typeof(UnityEngine.UIElements.VisualElement).IsAssignableFrom(type)) return null;
            while (type != null && (!type.IsVisible || type.IsGenericType)) type = type.BaseType;
            return type;
        }

        private static string GetTypeName(Type type)
        {
            if (type == null || type.FullName == null) return fallbackType;
            if (type.Namespace == uiElementsNamespace && !type.IsNested) return type.Name;
            return "global::" + type.FullName.Replace('+', '.');
        }

        private static bool IsEditorType(Type type)
        {
            string assembly = type.Assembly.GetName().Name;
            return assembly.StartsWith("UnityEditor") || assembly.StartsWith("Assembly-CSharp-Editor");
        }

        private static string ToLiteral(string value)
        {
            return "\"" + (value ?? string.Empty).Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        }
    }
}
